export function categorizeTireSize(size: string): TireCategory {
  const upper = size.toUpperCase();
  if (upper.includes('22.5') || upper.includes('R24') || upper.includes('1200R') || upper.includes('385/65') || upper.includes('315/80')) {
    return 'TBR (Truck & Bus)';
  }
  if (upper.includes('7.00R16') || upper.includes('7.50R16') || upper.includes('700R16') || upper.includes('750R16') || upper.includes('R14C') || upper.includes('R15C') || upper.includes('16PR')) {
    return 'Commercial & Van';
  }
  if (upper.includes('R19') || upper.includes('R20') || upper.includes('R21') || upper.includes('R22') || upper.includes('/40R18') || upper.includes('/45R18') || upper.includes('/35R20')) {
    return 'UHP (Performance)';
  }
  if (upper.includes('245/70') || upper.includes('265/70') || upper.includes('285/60') || upper.includes('275/60') || upper.includes('245/65') || upper.includes('265/60') || upper.includes('215/75')) {
    return 'SUV / 4x4';
  }
  return 'PCR (Passenger)';
}

